import { createServer } from 'node:http';
import { readFile, stat } from 'node:fs/promises';
import { extname, join } from 'node:path';
import { chromium } from 'playwright';
const base = '/PIXELAGENT-HUB/', [dist, out, model] = process.argv.slice(2);
const types: Record<string, string> = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.wasm': 'application/wasm', '.zip': 'application/zip' };
const server = createServer(async (req, res) => { let file = join(dist, decodeURIComponent(new URL(req.url!, 'http://x').pathname).slice(base.length)); try { if ((await stat(file)).isDirectory()) file = join(file, 'index.html'); res.writeHead(200, { 'content-type': types[extname(file)] || 'application/octet-stream' }).end(await readFile(file)); } catch { res.writeHead(404).end(); } });
await new Promise<void>((r) => server.listen(4424, '127.0.0.1', r));
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errors: string[] = []; p.on('pageerror', (e) => errors.push(e.message));
const t0 = Date.now();
await p.goto(`http://127.0.0.1:4424${base}#/studio?idea=${encodeURIComponent('A pixel counter with a big number, a +1 button and a Reset button.')}`);
await p.waitForSelector('.studio-stage');
await p.getByRole('button', { name: /BUILD LIVE/ }).click();
await p.locator('#live-provider').selectOption('custom');
await p.locator('#live-model').fill(model);
await p.getByRole('button', { name: /SAVE & BUILD/ }).click();
await p.waitForURL(/studio\/live-/);
await p.waitForFunction(() => /Built\. Ready to play|Run failed/.test(document.body.innerText), null, { timeout: 7_200_000, polling: 2000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: join(out, 'ollama-done.png'), fullPage: false });
console.log(JSON.stringify({ seconds: Math.round((Date.now() - t0) / 1000), stages: (await p.locator('.studio-stage').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ')), banner: await p.locator('.studio-replay-text').innerText(), errors: (await p.locator('.studio-error').allInnerTexts()).join(' | ').slice(0, 400), pageErrors: errors }));
await b.close(); server.close();
